// Helper to look up a service by id or alias
export function getServiceBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  return services.find(s => 
    s.id === cleanSlug || 
    s.slug === cleanSlug || 
    (s.aliases && s.aliases.includes(cleanSlug))
  ) || null;
}

